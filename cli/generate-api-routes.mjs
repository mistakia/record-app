// Writes src/shared/api-routes.ts: every method and path template in the
// pinned record-node 7-http-api.yaml, the allowlist the main process checks
// each renderer request against (spec §8.10.3). Run by `bun run gen:api`.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

import { parse } from 'yaml'

const SPEC_PATH = fileURLToPath(new URL('../node_modules/record-node/dist/api/7-http-api.yaml', import.meta.url))
const OUTPUT_PATH = fileURLToPath(new URL('../src/shared/api-routes.ts', import.meta.url))
const METHODS = ['get', 'head', 'post', 'put', 'patch', 'delete']

export const list_api_routes = (spec_text) => {
  const spec = parse(spec_text)
  const routes = []
  for (const [path_template, operations] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      if (operations[method] !== undefined) routes.push({ method, path_template })
    }
  }
  return routes
}

export const render_api_routes = (routes) => [
  '// Generated by cli/generate-api-routes.mjs from record-node\'s',
  '// dist/api/7-http-api.yaml. Do not edit; run `bun run gen:api`.',
  '',
  'export const API_ROUTES = [',
  ...routes.map(({ method, path_template }, index) =>
    `  { method: '${method}', path_template: '${path_template}' }${index === routes.length - 1 ? '' : ','}`),
  '] as const',
  ''
].join('\n')

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const routes = list_api_routes(await readFile(SPEC_PATH, 'utf8'))
  await writeFile(OUTPUT_PATH, render_api_routes(routes))
  console.log(`wrote ${routes.length} routes to ${OUTPUT_PATH}`)
}
